export async function verifyUvLockfile(projectPath: string): Promise<string> {
  try {
    const entries = await readdir(projectPath)
    const lockfiles = entries.filter((entry) => ['uv.lock', 'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lock', 'bun.lockb', 'poetry.lock', 'Pipfile.lock'].includes(entry))
    if (lockfiles.length !== 1 || lockfiles[0] !== 'uv.lock') throw new Error('Unexpected dependency lockfile set.')
    const lockPath = win32.join(projectPath, 'uv.lock')
    const info = await lstat(lockPath)
    if (!info.isFile() || info.isSymbolicLink()) throw new Error('uv.lock is not a regular file.')
    const lock = await readFile(lockPath, 'utf8')
    if (!/^version\s*=\s*1\s*$/m.test(lock) || !/^requires-python\s*=\s*"[^"]+"\s*$/m.test(lock)) throw new Error('uv.lock header is invalid.')
    const packages = lock.split(/(?=^\[\[package\]\]\s*$)/m)
    for (const [packageName, version] of directPins) {
      const block = packages.find((item) => new RegExp(`^name\\s*=\\s*"${packageName}"\\s*$`, 'm').test(item))
      if (!block || !new RegExp(`^version\\s*=\\s*"${version}"\\s*$`, 'm').test(block)
        || !/hash\s*=\s*"sha256:[a-f0-9]{64}"/.test(block)) throw new Error(`Locked package integrity is missing for ${packageName}@${version}.`)
    }
    return createHash('sha256').update(lock).digest('hex')
  } catch {
    throw new Error('Expected exactly one valid uv.lock with exact direct pins and SHA-256 package hashes.')
  }
}

export async function writeFastApiProjectManifest(
  stage: OwnedStage,
  resolved: ResolvedSelection,
  pythonVersion: string,
  uvVersion: string,
  lockHash: string,
  outcomes: readonly ValidationOutcome[],
  generatedFiles: readonly string[],
): Promise<void> {
  const manifest = {
    schemaVersion: 1,
    generatorVersion: '0.1.0',
    recipeId: resolved.recipe.id,
    recipeVersion: 1,
    recipeStatusAtCreation: resolved.recipe.status,
    createdAt: new Date().toISOString(),
    platform: `${process.platform}-${process.arch}`,
    projectName: resolved.selection.project.name,
    projectType: 'backend',
    documentationMode: resolved.selection.documentation,
    selectedAdapters: [{ id: 'backend.fastapi', version: '0.1.0' }],
    packageManager: 'uv',
    toolVersions: { python: pythonVersion, uv: uvVersion },
    upstreamSources: directPins.map(([packageName, resolvedVersion]) => ({ package: packageName, resolvedVersion, registry: 'https://pypi.org/' })),
    lockfiles: [{ name: 'uv.lock', sha256: lockHash }],
    generatedFiles: [...generatedFiles, '.project-generator/manifest.json'],
    validation: outcomes,
  }
  await mutateOwnedStage(stage, [], [{
    path: `${win32.basename(stage.childPath)}/.project-generator/manifest.json`,
    content: `${JSON.stringify(manifest, null, 2)}\n`,
  }])
}

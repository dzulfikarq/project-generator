const lockfileNames = [
  'composer.lock', 'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml',
  'bun.lock', 'bun.lockb', 'uv.lock', 'poetry.lock', 'Pipfile.lock',
]

function versionParts(version: string): [number, number, number] | undefined {
  const match = /^v?(\d+)\.(\d+)\.(\d+)/.exec(version)
  return match ? [Number(match[1]), Number(match[2]), Number(match[3])] : undefined
}

function atLeast(version: string, minimum: [number, number, number]): boolean {
  const parsed = versionParts(version)
  if (!parsed) return false
  for (let index = 0; index < minimum.length; index += 1) {
    if (parsed[index] !== minimum[index]) return parsed[index]! > minimum[index]!
  }
  return true
}

export interface ComposerLockEvidence {
  sha256: string
  frameworkVersion: string
  phpunitVersion: string
  packageCount: number
}

export async function verifyComposerLockfile(projectPath: string): Promise<ComposerLockEvidence> {
  const entries = await readdir(projectPath)
  const locks = entries.filter((entry) => lockfileNames.includes(entry))
  if (locks.length !== 1 || locks[0] !== 'composer.lock') throw new Error('Unexpected project lockfile set.')

  const lockPath = win32.join(projectPath, 'composer.lock')
  const info = await lstat(lockPath)
  if (!info.isFile() || info.isSymbolicLink()) throw new Error('composer.lock is not a regular file.')
  const [composerText, lockText] = await Promise.all([
    readFile(win32.join(projectPath, 'composer.json'), 'utf8'),
    readFile(lockPath, 'utf8'),
  ])
  const composer = JSON.parse(composerText) as {
    name?: string
    require?: Record<string, string>
    'require-dev'?: Record<string, string>
  }
  const lock = JSON.parse(lockText) as {
    'content-hash'?: string
    packages?: { name?: string; version?: string }[]
    'packages-dev'?: { name?: string; version?: string }[]
  }
  if (!/^forma\/[a-z0-9][a-z0-9._-]*$/.test(composer.name ?? '')
    || composer.require?.php !== LARAVEL_PINS.php
    || composer.require['laravel/framework'] !== LARAVEL_PINS.framework
    || composer.require['ext-pdo_mysql'] !== '*'
    || composer['require-dev']?.['phpunit/phpunit'] !== LARAVEL_PINS.phpunit
    || !/^[a-f0-9]{32}$/.test(lock['content-hash'] ?? '')
    || !Array.isArray(lock.packages) || !Array.isArray(lock['packages-dev'])) {
    throw new Error('composer.json or composer.lock metadata does not match the reviewed Laravel pins.')
  }
  const packages = [...lock.packages, ...lock['packages-dev']]
  const names = new Set<string>()
  for (const item of packages) {
    if (!item.name || !item.version || names.has(item.name)) throw new Error('Composer lock has missing or duplicate package identities.')
    names.add(item.name)
  }
  const frameworkVersion = packages.find(({ name }) => name === 'laravel/framework')?.version
  const phpunitVersion = packages.find(({ name }) => name === 'phpunit/phpunit')?.version
  const normalizedFramework = frameworkVersion?.replace(/^v/, '')
  if (normalizedFramework !== LARAVEL_PINS.framework || !phpunitVersion
    || !atLeast(phpunitVersion, [11, 5, 50]) || (versionParts(phpunitVersion)?.[0] ?? 0) >= 12) {
    throw new Error('Composer lock does not contain pinned Laravel 12 and a compatible PHPUnit 11 release.')
  }
  return {
    sha256: createHash('sha256').update(lockText).digest('hex'),
    frameworkVersion: normalizedFramework,
    phpunitVersion: phpunitVersion.replace(/^v/, ''),
    packageCount: packages.length,
  }
}


export async function writeLaravelProjectManifest(
  stage: OwnedStage,
  resolved: ResolvedSelection,
  phpVersion: string,
  composerVersion: string,
  lock: ComposerLockEvidence,
  outcomes: readonly ValidationOutcome[],
  generatedFiles: readonly string[],
): Promise<void> {
  const manifest = {
    schemaVersion: 1,
    generatorVersion: '0.1.0',
    recipeId: 'BE-05',
    recipeVersion: 1,
    recipeStatusAtCreation: 'planned',
    createdAt: new Date().toISOString(),
    platform: `${process.platform}-${process.arch}`,
    projectName: resolved.selection.project.name,
    projectType: 'backend',
    documentationMode: resolved.selection.documentation,
    selectedAdapters: [{ id: 'backend.laravel', version: '0.1.0' }],
    packageManager: 'composer',
    toolVersions: { php: phpVersion, composer: composerVersion, laravel: lock.frameworkVersion, phpunit: lock.phpunitVersion },
    upstreamSources: [
      { package: 'laravel/laravel', resolvedVersion: LARAVEL_PINS.scaffold, repository: 'https://github.com/laravel/laravel', commitSha: LARAVEL_PINS.scaffoldCommit },
      { package: 'laravel/framework', resolvedVersion: lock.frameworkVersion, registry: 'https://repo.packagist.org/' },
      { package: 'phpunit/phpunit', resolvedVersion: lock.phpunitVersion, registry: 'https://repo.packagist.org/' },
    ],
    dependencyFiles: ['composer.json'],
    lockfiles: [{ name: 'composer.lock', sha256: lock.sha256, packageCount: lock.packageCount }],
    generatedFiles: [...generatedFiles, '.project-generator/manifest.json'],
    validation: outcomes,
  }
  await mutateOwnedStage(stage, [], [{
    path: `${win32.basename(stage.childPath)}/.project-generator/manifest.json`,
    content: `${JSON.stringify(manifest, null, 2)}\n`,
  }])
}

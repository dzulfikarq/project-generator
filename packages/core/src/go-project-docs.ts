import { win32 } from 'node:path'
import { mutateOwnedStage, type OwnedStage } from './staging.js'
import type { ResolvedSelection, ValidationOutcome } from './types.js'

export async function writeGoProjectDocs(stage: OwnedStage, resolved: ResolvedSelection, goVersion: string): Promise<string[]> {
  const name = resolved.selection.project.name
  const modulePath = resolved.selection.backend?.modulePath ?? `example.com/${name}`
  const files = new Map<string, string>([
    ['README.md', `# ${name}\n\nStandalone Go REST API generated by FormaForge (BE-02). It uses Go's standard library only: no third-party dependencies, database, authentication, frontend, or deployment configuration.\n\n## Prerequisites\n\n- Go 1.22 or newer (generated with Go ${goVersion})\n- Go Modules\n\n## Run\n\n\`\`\`sh\ngo run ./cmd/server\n\`\`\`\n\nThe server reads HOST and PORT from the process environment. \.env.example documents defaults but is not loaded automatically.\n\n## API\n\n- \`GET /health\` — JSON process health.\n- \`GET /api/info\` — JSON service name and version.\n\nThe server logs requests, applies HTTP timeouts, and gracefully shuts down on interrupt or termination signals.\n\n## Verify\n\n\`\`\`sh\ngo fmt ./...\ngo vet ./...\ngo test ./...\ngo build ./...\n\`\`\`\n\nModule path: \`${modulePath}\`. No \`go.sum\` is generated because there are no external modules.\n`],
    ['docs/SETUP.md', `# Setup\n\n## Toolchain\n\nGo ${goVersion} generated this project. Go 1.22 or newer is required for method-aware \`net/http.ServeMux\` routes. Module path: \`${modulePath}\`.\n\n## Run\n\n\`\`\`sh\ngo run ./cmd/server\n\`\`\`\n\nDefault listener is \`127.0.0.1:3000\`. Set \`HOST\` and \`PORT\` in the process environment to change it. \.env.example is reference-only; no dotenv parser is included.\n\n## Validate\n\n\`\`\`sh\ngo fmt ./...\ngo vet ./...\ngo test ./...\ngo build ./...\n\`\`\`\n\nTests cover both JSON endpoints, 404 status, configured request timeouts, and graceful listener shutdown. Generation does not start the server after completion.\n`],
  ])

  if (resolved.selection.documentation !== 'minimal') {
    files.set('AGENTS.md', `# Agent instructions\n\n- Project: standalone Go REST API.\n- Module: \`${modulePath}\`; dependency management: Go Modules.\n- Run \`go fmt ./...\`, \`go vet ./...\`, and \`go test ./...\` before reporting changes.\n- No third-party dependencies, database, authentication, frontend, or deployment configuration.\n- Generated baseline is not an approval.\n`)
    files.set('docs/ARCHITECTURE.md', `# Architecture\n\nThe project uses standard-library \`net/http\` and Go 1.22+ method-aware routes. \`cmd/server/main.go\` reads HOST/PORT and owns signal handling. \`internal/server\` configures timeouts, request logging, routing, and graceful shutdown; \`internal/handlers\` serves JSON health and service information.\n\nGo Modules path: \`${modulePath}\`. There are no external modules and intentionally no \`go.sum\`.\n`)
    files.set('docs/TESTING.md', '# Testing\n\n- Format: `go fmt ./...`.\n- Static checks: `go vet ./...`.\n- Unit/integration tests: `go test ./...`.\n- Compile: `go build ./...`.\n- Generator smoke check starts the built server in owned staging and checks `/health` and `/api/info`; it stops before finalization.\n\nNo database or external service is required.\n')
  }
  if (resolved.selection.documentation === 'full') {
    files.set('CLAUDE.md', 'Read AGENTS.md and docs/ before changing this generated project. Do not claim checks passed unless you ran them.\n')
    files.set('agent.md', '# Agent notes\n\nInitial generated instructions only. No AI agent history or approval is asserted.\n')
    files.set('decision.md', '# Decision policy\n\nRecord future material decisions in docs/decisions/index.md. Generated baseline is not an approval.\n')
    files.set('design.md', '# Design notes\n\nStandalone Go API; no custom product UI requirements were supplied.\n')
    files.set('docs/PRD.md', `# Project brief\n\n- Project: ${name}\n- Stack: Go + net/http + Go Modules\n- Module: ${modulePath}\n- Scope: standalone API; no database, auth, frontend, or deployment configuration.\n- Status: initial generated project; no product approvals are implied.\n`)
    files.set('docs/decisions/index.md', '# Decision register\n\nNo material decisions or approvals have been recorded. Add entries only when decisions occur.\n')
    files.set('docs/qa/acceptance-matrix.md', '# Verification status\n\nSee `.project-generator/manifest.json` for checks executed during generation. No release approval is implied.\n')
  }

  const projectName = win32.basename(stage.childPath)
  const prefix = `${projectName}/`
  const written = await mutateOwnedStage(stage, [], [...files].map(([path, content]) => ({
    path: `${prefix}${path}`,
    content,
    replace: path === 'README.md',
    skipExisting: path !== 'README.md',
  })))
  return written.map((path) => path.slice(prefix.length))
}

export async function writeGoProjectManifest(
  stage: OwnedStage,
  resolved: ResolvedSelection,
  goVersion: string,
  outcomes: readonly ValidationOutcome[],
  generatedFiles: readonly string[],
): Promise<void> {
  const manifest = {
    schemaVersion: 1,
    generatorVersion: '0.1.0',
    recipeId: 'BE-02',
    recipeVersion: 1,
    recipeStatusAtCreation: 'planned',
    createdAt: new Date().toISOString(),
    platform: `${process.platform}-${process.arch}`,
    projectName: resolved.selection.project.name,
    projectType: 'backend',
    documentationMode: resolved.selection.documentation,
    selectedAdapters: [{ id: 'backend.go-net-http', version: '0.1.0' }],
    packageManager: 'go-modules',
    modulePath: resolved.selection.backend?.modulePath,
    toolVersions: { go: goVersion },
    upstreamSources: [],
    dependencyFiles: ['go.mod'],
    generatedFiles: [...generatedFiles, '.project-generator/manifest.json'],
    validation: outcomes,
  }
  await mutateOwnedStage(stage, [], [{
    path: `${win32.basename(stage.childPath)}/.project-generator/manifest.json`,
    content: `${JSON.stringify(manifest, null, 2)}\n`,
  }])
}
